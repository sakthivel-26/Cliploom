const assert = require('node:assert/strict');
const media = require('./docs/media-render.js');
assert.deepEqual(media.dimensions('vertical',1920,1080),{width:720,height:1280});
assert.deepEqual(media.dimensions('square',1920,1080),{width:720,height:720});
assert.deepEqual(media.dimensions('horizontal',0,0),{width:1280,height:720});
const left=media.crop(1920,1080,720,1280,0,50),right=media.crop(1920,1080,720,1280,100,50);
assert.equal(left.sx,0); assert.equal(left.sh,1080);
assert.equal(right.sx+right.sw,1920);
let texts=[],images=[];
const ctx={fillRect(){},drawImage(...args){images.push(args)},measureText:t=>({width:t.length*4}),fillText(...args){texts.push(args)},strokeText(){}};
const style={size:8,color:'#ffda58',shadow:true,x:32,y:28,cropX:100,cropY:50};
const lines=[{start:1,end:2,text:'தமிழ் hello'}],source={videoWidth:1920,videoHeight:1080};
assert.equal(media.draw({width:720,height:1280},ctx,source,.9,lines,style),false);
assert.equal(texts.length,0);
assert.equal(media.draw({width:720,height:1280},ctx,source,1,lines,style),true);
assert.equal(texts[0][0],'தமிழ் hello');
assert.ok(Math.abs(texts[0][1]-720*.32)<.001);
assert.ok(Math.abs(texts[0][2]-1280*.28)<.001);
assert.equal(ctx.font,'800 8px system-ui, sans-serif');
assert.equal(images.at(-1)[1],right.sx);
texts=[];
assert.equal(media.draw({width:720,height:1280},ctx,source,2,lines,style),false);
assert.equal(texts.length,0);
assert.deepEqual(media.wrap(ctx,'first\nsecond',100),['first','second']);
assert.ok(media.wrap(ctx,'averylongword',16).every(row=>ctx.measureText(row).width<=16));
assert.equal(media.draw({width:720,height:406},ctx,{videoWidth:0,videoHeight:0},1,lines,style),true);
console.log('PASS: crop bounds, output ratios, burnt-in text timing/position, Tamil text, audio-only rendering, long-word wrapping.');
